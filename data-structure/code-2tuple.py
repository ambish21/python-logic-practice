# TUPLES

# creating tuple
colors = ("red", "green", "blue")

print("Tuple:", colors)

# access element
print("First Color:", colors[0])

# loop through tuple
print("All Colors:")
for color in colors:
    print(color)

# length
print("Length:", len(colors))

# count element
print("Count of red:", colors.count("red"))

# index of element
print("Index of blue:", colors.index("blue"))