# slicing.py

text = "PythonProgramming"

# First character
print(text[0])

# Last character
print(text[-1])

# Characters from index 0 to 5
print(text[0:6])

# From index 6 to end
print(text[6:])

# Skip characters
print(text[::2])

# Reverse string
print(text[::-1])

# Middle part
print(text[6:17])

# Last 5 characters
print(text[-5:])